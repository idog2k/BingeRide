using static BingeRide.Workouts.Tests.TestUtil;

namespace BingeRide.Workouts.Tests;

public class JsonParserTests
{
    [Fact]
    public void Parses_metadata_and_every_step_type()
    {
        var result = Import("""
            {
              "format": "bingeride-workout", "version": 1, "name": "All types", "description": "d", "author": "Claude",
              "ftp": 250, "power_unit": "pct_ftp", "tags": ["a", "b"],
              "steps": [
                {"type": "steady", "sec": 300, "power": 60, "rpm": 90, "text": "Easy"},
                {"type": "ramp", "sec": 120, "from": 60, "to": 90},
                {"type": "slope", "sec": 180, "grade": 4.5, "gear": 9, "rpm": 70},
                {"type": "free", "m": 500, "grade": -1, "gear": 12}
              ]
            }
            """);

        Assert.Equal("json", result.Format);
        Assert.Empty(result.Warnings);
        var w = result.Workout;
        Assert.Equal("All types", w.Name);
        Assert.Equal("d", w.Description);
        Assert.Equal("Claude", w.Author);
        Assert.Equal(250, w.AuthorFtp);
        Assert.Equal(["a", "b"], w.Tags);
        Assert.Equal("json", w.SourceFormat);

        var s = w.Steps;
        Assert.Equal(4, s.Count);
        Assert.Equal(StepKind.Erg, s[0].Kind);
        Assert.Equal(300, s[0].DurationSec);
        Assert.Equal(PowerTarget.Percent(60), s[0].PowerStart);
        Assert.Equal(PowerTarget.Percent(60), s[0].PowerEnd);
        Assert.Equal(90, s[0].Cadence);
        Assert.Equal("Easy", s[0].Headline);
        Assert.Null(s[0].RepeatLabel);

        Assert.True(s[1].IsRamp);
        Assert.Equal((PowerTarget.Percent(60), PowerTarget.Percent(90)), (s[1].PowerStart!.Value, s[1].PowerEnd!.Value));

        Assert.Equal((StepKind.Slope, 180.0, 4.5, 9, 70), (s[2].Kind, s[2].DurationSec, s[2].Grade!.Value, s[2].Gear!.Value, s[2].Cadence!.Value));

        Assert.Equal(StepKind.Free, s[3].Kind);
        Assert.True(s[3].IsDistanceBased);
        Assert.Equal((500.0, -1.0, 12), (s[3].DistanceM, s[3].Grade!.Value, s[3].Gear!.Value));
    }

    [Fact]
    public void Lenient_syntax_comments_trailing_commas_case_and_aliases()
    {
        var result = Import("""
            // Generated by Claude
            {
              "Format": "BingeRide-Workout", "VERSION": 1, "Name": "Lenient", "Power_Unit": "pct_ftp",
              "Steps": [
                {"Type": "Steady", "Min": 1.5, "Power": 70,},   /* minutes, may be fractional */
                {"type": "steady", "duration": 45, "power": "80%"},
                {"type": "freeride", "min": 2},
              ],
            }
            """);

        Assert.Empty(result.Warnings);
        var s = result.Workout.Steps;
        Assert.Equal([90.0, 45.0, 120.0], s.Select(x => x.DurationSec));
        Assert.Equal(PowerTarget.Percent(70), s[0].PowerStart);
        Assert.Equal(PowerTarget.Percent(80), s[1].PowerStart);
        Assert.Equal(StepKind.Free, s[2].Kind);
    }

    [Fact]
    public void Missing_format_and_version_are_warnings()
    {
        var result = Import("""{"name": "x", "power_unit": "pct_ftp", "steps": [{"type": "steady", "sec": 60, "power": 50}]}""");
        Assert.Contains(result.Warnings, w => w.Contains("\"format\""));
        Assert.Contains(result.Warnings, w => w.Contains("\"version\""));
    }

    [Fact]
    public void Small_pct_values_are_read_as_fractions()
    {
        var result = Import(Json("""{"type":"steady","sec":60,"power":0.75},{"type":"ramp","sec":60,"from":0.5,"to":1.2}"""));
        var s = result.Workout.Steps;
        Assert.Equal(PowerTarget.Percent(75), s[0].PowerStart);
        Assert.Equal((PowerTarget.Percent(50), PowerTarget.Percent(120)), (s[1].PowerStart!.Value, s[1].PowerEnd!.Value));
        Assert.Single(result.Warnings, w => w.Contains("fractions of FTP"));
    }

    [Fact]
    public void Reads_files_from_before_the_rename_without_a_warning()
    {
        var result = Import("""{"format":"mywahoo-workout","version":1,"name":"Old","power_unit":"pct_ftp","steps":[{"type":"steady","sec":60,"power":50}]}""");
        Assert.Equal("Old", result.Workout.Name);
        Assert.Empty(result.Warnings);
    }

    [Fact]
    public void Missing_power_unit_infers_pct_ftp_when_all_values_are_at_most_300()
    {
        var result = Import("""{"format":"bingeride-workout","version":1,"name":"x","steps":[{"type":"steady","sec":60,"power":300},{"type":"ramp","sec":60,"from":50,"to":80}]}""");
        Assert.Equal(PowerTarget.Percent(300), result.Workout.Steps[0].PowerStart);
        Assert.Contains(result.Warnings, w => w.Contains("pct_ftp"));
    }

    [Fact]
    public void Missing_power_unit_infers_watts_when_a_value_exceeds_300()
    {
        var result = Import("""{"format":"bingeride-workout","version":1,"name":"x","steps":[{"type":"steady","sec":60,"power":150},{"type":"repeat","times":2,"steps":[{"type":"steady","sec":30,"power":320}]}]}""");
        Assert.Equal(PowerTarget.Watts(150), result.Workout.Steps[0].PowerStart);
        Assert.Equal(PowerTarget.Watts(320), result.Workout.Steps[1].PowerStart);
        Assert.Contains(result.Warnings, w => w.Contains("watts"));
    }

    [Fact]
    public void Watts_unit_produces_watt_targets()
    {
        var result = Import(Json("""{"type":"steady","sec":60,"power":2.5}""", unit: "watts"));
        Assert.Equal(PowerTarget.Watts(2.5), result.Workout.Steps[0].PowerStart);
    }

    [Fact]
    public void Repeats_are_flattened_with_labels_and_the_repeat_text_on_the_first_step()
    {
        var result = Import(Json("""
            {"type":"steady","sec":60,"power":50},
            {"type":"repeat","times":3,"text":"Main set","steps":[
              {"type":"steady","sec":60,"power":100,"text":"On"},
              {"type":"steady","sec":30,"power":50}]}
            """));
        var s = result.Workout.Steps;
        Assert.Equal(7, s.Count);
        Assert.Equal([null, "1/3", "1/3", "2/3", "2/3", "3/3", "3/3"], s.Select(x => x.RepeatLabel));
        Assert.Equal(["On", "Main set"], s[1].Cues.Select(c => c.Text));
        Assert.Equal("On", s[1].Headline);
        Assert.Equal(["On"], s[3].Cues.Select(c => c.Text));
        Assert.Equal(60 + 3 * 90, result.Workout.TotalDurationSec);
    }

    [Fact]
    public void Repeat_cues_are_placed_relative_to_the_block_start()
    {
        var result = Import(Json("""
            {"type":"repeat","times":2,"cues":[{"at":70,"text":"Keep going"}],"steps":[
              {"type":"steady","sec":60,"power":100},{"type":"steady","sec":60,"power":50}]}
            """));
        Assert.Equal(new WorkoutCue(10, "Keep going"), Assert.Single(result.Workout.Steps[1].Cues));
    }

    [Fact]
    public void Nested_repeat_is_an_error()
    {
        var ex = Fails(Json("""{"type":"repeat","times":2,"steps":[{"type":"repeat","times":2,"steps":[{"type":"steady","sec":60,"power":50}]}]}"""));
        Assert.Contains("steps[0].steps[0] (repeat)", ex.Message);
        Assert.Contains("one level", ex.Message);
    }

    [Fact]
    public void Cues_are_sorted_and_a_late_cue_warns()
    {
        var result = Import(Json("""{"type":"steady","sec":120,"power":80,"text":"Go","cues":[{"at":200,"text":"Late"},{"at":60,"text":"Halfway"}]}"""));
        Assert.Equal([(0.0, "Go"), (60.0, "Halfway"), (200.0, "Late")], result.Workout.Steps[0].Cues.Select(c => (c.OffsetSec, c.Text)));
        Assert.Contains(result.Warnings, w => w.Contains("past the end"));
    }

    [Fact]
    public void Unknown_properties_and_missing_type_are_warnings()
    {
        var result = Import(Json("""{"sec":60,"power":50,"colour":"red"},{"from":50,"to":60,"sec":60}"""));
        Assert.Contains(result.Warnings, w => w.Contains("unknown property \"colour\""));
        Assert.Contains(result.Warnings, w => w.Contains("treated as \"steady\""));
        Assert.Contains(result.Warnings, w => w.Contains("treated as \"ramp\""));
        Assert.True(result.Workout.Steps[1].IsRamp);
    }

    [Fact]
    public void Missing_name_falls_back_to_the_file_name()
    {
        var result = Import("""{"format":"bingeride-workout","version":1,"power_unit":"pct_ftp","steps":[{"type":"steady","sec":60,"power":50}]}""", "C:\\workouts\\my-ride.json");
        Assert.Equal("my-ride", result.Workout.Name);
        Assert.Contains(result.Warnings, w => w.Contains("\"name\""));
    }

    [Theory]
    [InlineData("""{"type":"steady","sec":60}""", "steps[0] (steady): \"power\" is required")]
    [InlineData("""{"type":"sprint","sec":60}""", "unknown step type \"sprint\"")]
    [InlineData("""{"type":"steady","m":500,"power":60}""", "ERG steps must be time-based")]
    [InlineData("""{"type":"steady","sec":60,"min":1,"power":60}""", "only one of")]
    [InlineData("""{"type":"steady","power":60}""", "needs a duration")]
    [InlineData("""{"type":"steady","sec":-5,"power":60}""", "must be positive")]
    [InlineData("""{"type":"steady","sec":60,"power":"lots"}""", "\"power\" must be a number")]
    [InlineData("""{"type":"slope","sec":60}""", "\"grade\" is required")]
    [InlineData("""{"type":"repeat","times":0,"steps":[{"type":"steady","sec":60,"power":50}]}""", "\"times\" must be between")]
    [InlineData("""{"type":"repeat","times":2.5,"steps":[{"type":"steady","sec":60,"power":50}]}""", "whole number")]
    [InlineData("""{"type":"repeat","times":2,"steps":[]}""", "non-empty array")]
    [InlineData("""{"type":"steady","sec":60,"power":50,"cues":[{"at":-1,"text":"x"}]}""", "can't be negative")]
    [InlineData("""42""", "each step must be an object")]
    public void Step_errors_name_the_step(string step, string expected)
    {
        var ex = Fails(Json(step));
        Assert.Contains(expected, ex.Message);
    }

    [Theory]
    [InlineData("""{"type":"slope","sec":60,"grade":30}""", "grade 30 % is outside")]
    [InlineData("""{"type":"free","sec":60,"gear":30}""", "gear 30 is outside")]
    [InlineData("""{"type":"steady","sec":60,"power":350}""", "350 % FTP is above")]
    [InlineData("""{"type":"steady","sec":0.5,"power":50}""", "at least 1 s")]
    public void Validation_errors_are_thrown(string step, string expected)
    {
        var ex = Fails(Json(step));
        Assert.Contains(expected, ex.Message);
        Assert.Contains("Step 1", ex.Message);
    }

    [Fact]
    public void Invalid_json_reports_the_line()
    {
        var ex = Fails("""
            {
              "name": "x",
              "steps": [ {"type": "steady" "sec": 60} ]
            }
            """, "x.json");
        Assert.Contains("Invalid JSON at line 3", ex.Message);
    }

    [Theory]
    [InlineData("""[1, 2]""", "must be a JSON object")]
    [InlineData("""{"name":"x"}""", "needs a \"steps\" array")]
    [InlineData("""{"name":"x","steps":[]}""", "empty")]
    [InlineData("""{"name":"x","power_unit":"kcal","steps":[{"type":"steady","sec":60,"power":50}]}""", "Unknown \"power_unit\"")]
    public void Document_errors(string json, string expected)
    {
        Assert.Contains(expected, Fails(json, "x.json").Message);
    }
}
